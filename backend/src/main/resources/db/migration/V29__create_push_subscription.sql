-- Recordatorios push de citas: dispositivos suscritos (un usuario puede tener varios) y marca de
-- "recordatorio ya enviado" por cita, para no avisar dos veces aunque haya varias instancias.
create table push_subscription (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    endpoint text not null,
    p256dh varchar(255) not null,
    auth varchar(255) not null,
    user_agent varchar(255),
    created_at timestamp(6) with time zone not null,
    constraint fk_push_subscription_user foreign key (user_id) references user_app,
    constraint uk_push_subscription_endpoint unique (endpoint)
);
create index idx_push_subscription_user_id on push_subscription (user_id);

alter table appointment add column reminder_sent_at timestamp(6) with time zone;
create index idx_appointment_reminder_due on appointment (start_time) where reminder_sent_at is null;
