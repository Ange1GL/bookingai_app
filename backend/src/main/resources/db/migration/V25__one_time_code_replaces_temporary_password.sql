-- El alta y el reinicio de usuarios dejan de generar una contrasena temporal: ahora se emite un codigo de un
-- solo uso (OTP) por WhatsApp con el que el usuario CREA su propia contrasena. El OTP vive en su propia tabla
-- (normalizado: ni el hash ni la caducidad ni los intentos van en user_app) y su proposito en un catalogo, igual
-- que status_appointment <-> domain.model.StatusAppointment.

-- Catalogo de propositos. Debe reflejar 1:1 el enum domain.model.OneTimeCodePurpose (mapeo por purpose_id).
create table one_time_code_purpose
(
    purpose_id integer      not null,
    name       varchar(50)  not null,
    constraint pk_one_time_code_purpose primary key (purpose_id),
    constraint uk_one_time_code_purpose_name unique (name)
);

insert into one_time_code_purpose (purpose_id, name)
values (1, 'ACCOUNT_ACTIVATION'),
       (2, 'PASSWORD_RESET');

create table one_time_code
(
    one_time_code_id bigint generated by default as identity,
    user_id          bigint                   not null,
    purpose_id       integer                  not null,
    code_hash        varchar(100)             not null,
    expires_at       timestamp(6) with time zone not null,
    failed_attempts  smallint                 not null default 0,
    consumed_at      timestamp(6) with time zone,
    created_at       timestamp(6) with time zone not null,
    constraint pk_one_time_code primary key (one_time_code_id),
    constraint fk_one_time_code_user foreign key (user_id) references user_app (user_id),
    constraint fk_one_time_code_purpose foreign key (purpose_id) references one_time_code_purpose (purpose_id)
);

-- Como maximo un codigo vigente por usuario: emitir uno nuevo consume (invalida) el anterior.
create unique index uk_one_time_code_pending_per_user on one_time_code (user_id) where consumed_at is null;
create index idx_one_time_code_user_id on one_time_code (user_id);

-- "Debe cambiar la contrasena" era un dato derivado: ahora una cuenta sin contrasena (password IS NULL) es una
-- cuenta pendiente de crearla con un OTP. Los usuarios que aun tenian una temporal quedan sin contrasena y
-- el admin les envia un codigo con reset-password.
update user_app set password = null where must_change_password;
alter table user_app drop column must_change_password;
