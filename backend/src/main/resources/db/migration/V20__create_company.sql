-- Negocio (compañía) de un usuario. Una compañía por usuario; los clientes de WhatsApp la buscan por nombre.
create table company (
    company_id bigint generated by default as identity primary key,
    name varchar(100) not null,
    user_id bigint not null,
    created_at timestamp(6) with time zone,
    constraint fk_company_user foreign key (user_id) references user_app,
    constraint uk_company_user_id unique (user_id)
);
create index idx_company_name_lower on company (lower(name));
