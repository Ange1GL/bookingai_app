-- Datos de contacto del usuario: ahora lleva apellidos, el correo es opcional (el canal real es el telefono) y los
-- telefonos se guardan siempre con prefijo de pais. Ademas, se registran las solicitudes de recuperacion de
-- contrasena para que el administrador las atienda reiniciando la contrasena con un codigo de un solo uso.

alter table user_app add column last_name varchar(255);

-- email unique sigue vigente: PostgreSQL permite varias filas con email NULL.
alter table user_app alter column email drop not null;

-- Telefonos nacionales de 10 digitos guardados antes de este cambio: se les antepone el prefijo de Mexico (52).
update user_app set phone = '52' || phone where phone ~ '^[0-9]{10}$';

create table password_recovery_request
(
    password_recovery_request_id bigint generated by default as identity,
    user_id                      bigint                      not null,
    requested_at                 timestamp(6) with time zone not null,
    resolved_at                  timestamp(6) with time zone,
    constraint pk_password_recovery_request primary key (password_recovery_request_id),
    constraint fk_password_recovery_request_user foreign key (user_id) references user_app (user_id)
);

-- A lo mucho una solicitud pendiente por usuario: pedirla varias veces no llena la bandeja del administrador.
create unique index uk_password_recovery_request_pending_per_user
    on password_recovery_request (user_id) where resolved_at is null;
